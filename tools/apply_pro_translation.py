errors = []
for eid, text in translations.items():
    for pi, page in enumerate(text.split('\f')):
        for li, line in enumerate(page.split('\n')):
            l = line.strip()
            if len(l) > 20:
                errors.append(f"[{eid}] page {pi} line {li} (len {len(l)} > 20): {repr(l)}")

if errors:
    print(f"Validation FAILED with {len(errors)} errors:")
    for err in errors:
        print("  " + err)
    raise SystemExit(1)
else:
    print("ALL TRANSLATIONS VALIDATED! Every single line is <= 20 characters.")

